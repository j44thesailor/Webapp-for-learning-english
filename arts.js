// Cách thêm: copy nguyên 1 block "ARTS.push(art(function(){ ... }));" bên dưới,
// rồi dán art vào giữa cặp comment (slash-star ... star-slash).
// Không cần escape gì cả (backtick, backslash, $ đều OK).
// Chỉ cấm đúng 1 thứ: chuỗi star-slash nằm trong art.
// Indent thừa và dòng trống đầu/cuối tự được cắt.

window.ARTS = [];

function art(fn) {
  const s = fn.toString();
  const body = s.slice(s.indexOf('/*') + 2, s.lastIndexOf('*/'));
  let lines = body.replace(/\r/g, '').split('\n').map(l => l.replace(/\s+$/, ''));
  while (lines.length && !lines[0].trim()) lines.shift();
  while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
  const indent = Math.min(...lines.filter(l => l.trim()).map(l => l.match(/^ */)[0].length));
  return lines.map(l => l.slice(indent)).join('\n');
}

